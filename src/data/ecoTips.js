// Simple helper to get a Tip of the Day based on the current calendar day
// (so it changes once per day, or can be randomly selected on button press)
export function getTipOfDay(forcedIndex = -1) {
  if (forcedIndex >= 0 && forcedIndex < ecoTips.length) {
    return ecoTips[forcedIndex];
  }
  // Default: Choose tip based on current date
  const day = new Date().getDate();
  const index = day % ecoTips.length;
  return ecoTips[index];
}
